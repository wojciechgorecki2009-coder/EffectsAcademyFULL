/*
 * Copies the After Effects extension's panel (HTML, CSS, JS and preview assets) into
 * public/extension-demo/, where the "Test Extension" page shows it in an iframe.
 *
 * The copy is the real panel. public/extension-demo/demo.js and demo.css (kept in that
 * folder, not copied) switch it to demo mode: buttons explain what they would do, and
 * nothing is downloaded or sent to After Effects.
 *
 * Runs before `start` and `build`. When ../after-effects-extension isn't there (a deploy
 * that only has the frontend folder), the committed copy is used as it is.
 */
const fs = require("fs");
const path = require("path");

const SOURCE = path.resolve(__dirname, "..", "..", "after-effects-extension");
const TARGET = path.resolve(__dirname, "..", "public", "extension-demo");

// Only what the panel needs in a browser: no binaries, no ExtendScript, no OBJ converter.
const FILES = [
  "styles.css",
  "js/app.js",
  "js/expressions.js",
  "js/expressions-window.js",
  "js/models.js",
  "js/clipboard.js",
  "assets/favicon.png",
];
const FOLDERS = ["assets/expressions"];

function copy(relative) {
  const from = path.join(SOURCE, relative);
  const to = path.join(TARGET, relative);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

// Turns one of the extension's pages into its demo version: demo.css and demo.js are added
// before the page's own script, and the shared session file (which needs After Effects'
// Node access) is left out.
function demoPage(name, html, firstScript) {
  const replaceOnce = (text, search, replacement) => {
    if (!text.includes(search)) throw new Error(`extension ${name} no longer contains: ${search}`);
    return text.replace(search, replacement);
  };
  let out = html;
  out = replaceOnce(out, '<meta charset="utf-8" />', '<meta charset="utf-8" />\n    <meta name="robots" content="noindex" />');
  out = replaceOnce(out, '<link rel="stylesheet" href="./styles.css" />', '<link rel="stylesheet" href="./styles.css" />\n    <link rel="stylesheet" href="./demo.css" />');
  out = replaceOnce(out, '    <script src="./js/session-share.js"></script>\n', "");
  out = replaceOnce(out, `<script src="./js/${firstScript}"></script>`, `<script src="./demo.js"></script>\n    <script src="./js/${firstScript}"></script>`);
  return replaceOnce(out, "<!doctype html>\n", `<!doctype html>\n<!-- Generated by frontend/scripts/sync-extension-demo.js from after-effects-extension/${name}. Edit that file, not this one. -->\n`);
}

// [page, the first of its own scripts]
const PAGES = [
  ["index.html", "app.js"],
  ["expressions.html", "expressions-window.js"],
];

function main() {
  if (!fs.existsSync(path.join(SOURCE, "index.html"))) {
    console.log("[extension-demo] after-effects-extension not found; using the committed copy.");
    return;
  }
  FILES.forEach(copy);
  FOLDERS.forEach((folder) => {
    fs.readdirSync(path.join(SOURCE, folder)).forEach((name) => copy(path.join(folder, name)));
  });
  PAGES.forEach(([name, firstScript]) => {
    const html = fs.readFileSync(path.join(SOURCE, name), "utf8").replace(/\r\n/g, "\n");
    fs.writeFileSync(path.join(TARGET, name), demoPage(name, html, firstScript));
  });
  console.log("[extension-demo] Copied the extension panel into public/extension-demo.");
}

main();
